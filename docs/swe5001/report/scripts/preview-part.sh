#!/usr/bin/env bash
# Render one part of Appendix A to PNG pages and report each diagram's print size.
#
#   docs/swe5001/report/scripts/preview-part.sh a06          (or a06-uc4, or a06-uc4.typ)
#   FULL=1 docs/swe5001/report/scripts/preview-part.sh a06   (inside the whole report; slower)
#   PPI=150 …                                                (sharper pages; default 110)
#   NOGEN=1 …                                                (skip regenerating diagrams)
#
# 1. Regenerates every diagram from diagrams/appendix-a/src. A failing source is reported and
#    keeps its last generated drawing, so another writer's broken diagram does not stop you.
# 2. By default sets the part alone: the appendix without chapters 1-6 and without the other
#    parts (--input apart=<part>, see sections/07-appendix-a.typ). The part keeps its own number;
#    its figures and tables count from A.1; a reference to a label outside the part prints as a
#    red "?label". Fast, and immune to errors in other parts. FULL=1 compiles the whole report
#    instead (real numbers and references, and a PDF at build/preview-<part>.pdf); if that fails
#    it prints the error and falls back to the part alone.
# 3. Writes only the part's pages to PREVIEW_DIR/<part>/page-NNN.png. PREVIEW_DIR defaults to
#    .build/swe5001-appendix/preview in the main checkout (the parent of the shared .git).
# 4. Prints the compiler's warnings, then one line per figure: id, page, kind, scale and label
#    size; "SMALL" marks labels below the 8 pt minimum.
set -euo pipefail

part="${1:?usage: preview-part.sh <part, e.g. a06>}"
part="${part%.typ}"
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
report="$(cd "$here/.." && pwd)"
repo="$(cd "$report/../../.." && pwd)"
cd "$repo"

file="$(ls "$report/sections/appendix-a/" | grep -E "^${part}(-|\.typ$)" | head -n 1 || true)"
if [[ -z "$file" ]]; then
  echo "no part file matching '$part' in $report/sections/appendix-a" >&2
  exit 1
fi
name="${file%.typ}"

common="$(cd "$(git rev-parse --git-common-dir)" && pwd)"
out="${PREVIEW_DIR:-$(dirname "$common")/.build/swe5001-appendix/preview}/$name"
build="$report/build"
mkdir -p "$out" "$build"
rm -f "$out"/page-*.png

if [[ -z "${NOGEN:-}" ]]; then
  if ! node "$report/scripts/appendix-diagrams.mjs" >"$build/preview-$name.gen.log" 2>&1; then
    grep -E "^FAIL" "$build/preview-$name.gen.log" || cat "$build/preview-$name.gen.log"
    echo "--- the diagrams above failed; their last generated drawing is used ---"
  fi
fi

# The appendix alone: lib.typ styles, no chapters 1-6. Shared by all writers; content is fixed.
alone="$build/preview-alone.typ"
printf '%s\n' \
  '// Generated by scripts/preview-part.sh: the appendix without chapters 1-6. Do not edit.' \
  '#import "/docs/swe5001/report/lib.typ": *' \
  '#show: style' \
  '#include "/docs/swe5001/report/sections/07-appendix-a.typ"' >"$alone.$$"
mv "$alone.$$" "$alone"

log="$build/preview-$name.log"
main="$alone"
inputs=(--input "apart=$name")
mode="alone"
if [[ -n "${FULL:-}" ]]; then
  if typst compile --root . "$report/main.typ" "$build/preview-$name.pdf" 2>"$log"; then
    main="$report/main.typ"
    inputs=()
    mode="full report"
  else
    echo "--- the full report does not compile; setting $name alone ---"
    cat "$log"
  fi
fi

# One compile answers every question: the part markers, the page count and the figure notes.
if ! info="$(typst eval --root . ${inputs[@]+"${inputs[@]}"} \
  "(parts: query(<a-part>).map(it => it.value), total: query(<a-pages>).first().value, figs: query(<a-fig>).map(it => it.value))" \
  --in "$main" 2>"$log")"; then
  cat "$log" >&2
  exit 1
fi
if grep -q "warning" "$log"; then
  echo "--- compiler output (fix every warning) ---"
  cat "$log"
fi

# The part runs from its marker's page to the next part's marker, extended to the last page that
# holds one of its figures (a landscape page may land after the next part begins) plus one page
# for a float that moved on (a float reports the page it was called on).
range="$(node -e '
  const { parts, total, figs } = JSON.parse(process.argv[1]);
  const i = parts.findIndex((p) => p.part === process.argv[2]);
  if (i < 0) { console.error("part not in 07-appendix-a.typ: " + process.argv[2]); process.exit(1); }
  const start = parts[i].page;
  const next = (parts[i + 1] || parts[i]).page;
  const own = figs.filter((f) => f.anchor >= start && f.anchor <= next).map((f) => f.page);
  console.log(`${start}-${Math.min(total, Math.max(start, next, ...own) + 1)}`);
' "$info" "$name")"

typst compile --root . ${inputs[@]+"${inputs[@]}"} "$main" "$out/page-{0p}.png" --pages "$range" --ppi "${PPI:-110}" 2>/dev/null
echo "part $name ($mode): pages $range -> $out"

node -e '
  const { figs } = JSON.parse(process.argv[1]);
  const [a, b] = process.argv[2].split("-").map(Number);
  const mine = figs.filter((f) => f.anchor >= a && f.anchor <= b);
  if (!mine.length) { console.log("no generated diagrams on these pages"); process.exit(0); }
  for (const f of mine) {
    const s = f.scale == null ? 1 : f.scale;
    const pt = (8.5 * s).toFixed(1);
    const flag = 8.5 * s < 7.995 ? "  SMALL: split the diagram or narrow its members" : "";
    console.log(`${f.id.padEnd(26)} p${String(f.page).padEnd(4)} ${f.kind.padEnd(8)} scale ${s.toFixed(2)}  labels ${pt} pt${f.landscape ? "  landscape" : ""}${flag}`);
  }
' "$info" "$range"
ls "$out" | tr '\n' ' '
echo
