// Generate Liu Jin's speaker script (Typst) from the deck's content.js, so the two cannot drift.
// Usage (repository root): node docs/swe5006/presentation/speaker-scripts/build.js docs/swe5006/presentation docs/swe5006/presentation/speaker-scripts/liu-jin.typ "<source label>"
// then: typst compile docs/swe5006/presentation/speaker-scripts/liu-jin.typ
const path = require('path');
const fs = require('fs');
const [deckDir, out, base] = process.argv.slice(2);
const c = require(path.resolve(deckDir, 'src/content.js'));
const { slideClock, est, hms } = require(path.resolve(deckDir, '../../presentation-kit/lib/schedule.js'));

const ME = 'Liu Jin';
const clock = slideClock(c.SEGMENTS, c.SLIDES);
const mine = c.SLIDES.filter(s => s.speaker === ME);
const byN = n => c.SLIDES.find(s => s.n === n);
const clk = t => hms(t);

// Typst string literal.
const q = s => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, ' ') + '"';
// Allow line breaks inside long identifiers (after dots, and before capitals in words over 30 characters).
const ZW = '\u200b';
const brk = s => s.replace(/\.(?=[A-Za-z])/g, '.' + ZW).replace(/[A-Za-z]{31,}/g, w => w.replace(/(?<=[a-z])(?=[A-Z])/g, ZW));
// Split text into parts: plain text, clicks and draft markers, for the Typst `rich` function.
function parts(s) {
  const re = /(\[click(?: \d+\/\d+)?\])|\{\{(FILL|VERIFY|CONFIRM):([^}]*)\}\}/g;
  const res = [];
  let i = 0, m;
  while ((m = re.exec(s))) {
    if (m.index > i) res.push(['t', brk(s.slice(i, m.index))]);
    if (m[1]) res.push(['c', m[1].slice(1, -1)]);
    else res.push([m[2].toLowerCase(), m[3]]);
    i = re.lastIndex;
  }
  if (i < s.length) res.push(['t', brk(s.slice(i))]);
  return '(' + res.map(p => `(${q(p[0])}, ${q(p[1])})`).join(', ') + (res.length === 1 ? ',' : '') + ')';
}
const words = s => s.replace(/\[click(?: \d+\/\d+)?\]/g, '').split(/\s+/).filter(Boolean).length;

const rows = Object.entries(c.QA).flatMap(([seg, v]) => v.rows.map(r => ({ seg, q: r[0], a: r[1], who: r[2] })));
const myQa = rows.filter(r => r.who.includes(ME));
const myItems = c.OPEN_ITEMS.filter(r => String(r[2]).includes(ME));

let t = `// Generated by speaker-scripts/build.js from docs/swe5006/presentation/src/content.js (${base}). Edit content.js and regenerate; do not edit by hand.
#set document(title: "SWE5006 presentation — Liu Jin's speaker script", author: "Liu Jin")
#set page(paper: "a4", margin: (x: 18mm, y: 16mm), numbering: "1 / 1",
  header: context { if counter(page).get().first() > 1 [#text(8pt, fill: luma(110))[BlocBuy · SWE5006 presentation · Liu Jin's script #h(1fr) Mon 26 Oct 2026, 16:30 SGT]] })
#set text(font: ("Helvetica Neue", "Arial"), size: 10pt, lang: "en")
#set par(justify: false, leading: 0.6em)
#show heading.where(level: 1): set text(15pt)
#show heading.where(level: 2): set text(12.5pt)

#let accent = rgb("#3E5CD9")
#let warn = rgb("#B02E1B")
#let chip(body, fill, stroke) = box(inset: (x: 3pt, y: 1.5pt), radius: 2pt, fill: fill, stroke: stroke, text(8.5pt, font: ("Menlo",), body))
#let rich(ps, size: 10pt) = for p in ps {
  let (k, s) = p
  if k == "t" { text(size, s) }
  else if k == "c" { chip(text(fill: accent, weight: "bold", s), rgb("#E3E8FB"), none) }
  else if k == "fill" { chip([FILL: #s], rgb("#FDEFEC"), (paint: warn, dash: "dashed")) }
  else if k == "verify" { chip([VERIFY: #s], rgb("#FFF6DD"), (paint: rgb("#9A6B00"), dash: "dashed")) }
  else { chip([CONFIRM: #s], rgb("#EEF7EE"), (paint: rgb("#2E7D32"), dash: "dashed")) }
}
#let lbl(s) = text(8pt, weight: "bold", fill: luma(100), upper(s))

= Liu Jin — speaker script

#text(9.5pt, fill: luma(90))[SWE5006 Practice Project presentation, Team 8 BlocBuy, Monday 26 October 2026, 16:30–17:10 SGT (Zoom). My part: the full-form design problem and the schema (§2), then all of §3, testing. Source: ${base}. Speaking time is estimated at 130 words a minute. Markers (FILL, VERIFY, CONFIRM) must be gone after the 25 Oct rehearsal.]

== Run of show

#table(columns: (auto, auto, auto, auto, 1fr, auto), stroke: 0.4pt + luma(200), inset: 5pt,
  table.header([*Slide*], [*Clock*], [*Slot*], [*Est.*], [*Title*], [*Rubric*]),
${mine.map(s => `  [${s.n}], [${clk(clock[s.n][0])}], [${s.slot} s], [${est(s)} s], [${s.title.replace(/[\[\]#*_@<>$\\]/g, m => '\\' + m)}], [${(s.rubric || []).join(', ')}],`).join('\n')}
)
#text(9pt)[Total slots ${mine.reduce((a, s) => a + s.slot, 0)} s; estimated speech ${mine.reduce((a, s) => a + est(s), 0)} s. I come in after ${byN(mine[0].n - 1).speaker} (slide ${mine[0].n - 1}) and hand over to ${byN(mine[mine.length - 1].n + 1).speaker} (slide ${mine[mine.length - 1].n + 1}).]
`;

for (const s of mine) {
  const prev = byN(s.n - 1), next = byN(s.n + 1);
  t += `
#v(6pt)
#block(breakable: true, width: 100%, stroke: (left: 2pt + accent), inset: (left: 9pt, y: 4pt))[
== Slide ${s.n} · ${s.title.replace(/[\[\]#*_@<>$\\]/g, m => '\\' + m)}
#text(9pt, fill: luma(90))[${clk(clock[s.n][0])}–${clk(clock[s.n][1])} · slot ${s.slot} s · estimate ${est(s)} s (${words(s.say)} words) · rubric ${(s.rubric || []).join(', ')}]
${prev.speaker !== ME ? `\n#lbl("Cue in") #h(4pt) #rich(${parts(prev.handover || '')}, size: 9.5pt)\n` : ''}
#lbl("Say")
#block(inset: (y: 3pt))[#set par(leading: 0.75em); #rich(${parts(s.say)}, size: 12pt)]
${s.trim ? `#lbl("If over time") #h(4pt) #rich(${parts(s.trim)}, size: 9.5pt)\n` : ''}
${s.handover ? `#lbl("Hand over") #h(4pt) #rich(${parts(s.handover)}, size: 9.5pt) #h(1fr) #text(8.5pt, fill: luma(110))[next: slide ${next.n}, ${next.speaker}]\n` : ''}
#lbl("Cues")
#text(8.8pt)[${(s.cues || []).map(x => `\n- #rich(${parts(x)}, size: 8.8pt)`).join('')}
]
]
`;
}

t += `
#pagebreak()
== Questions I answer

#text(9pt, fill: luma(90))[Answer in 30–45 s: decision, reason, evidence or limitation. "A → B" means A starts and B adds.]

#table(columns: (30%, 1fr, 13%), stroke: 0.4pt + luma(200), inset: 5pt,
  table.header([*Question*], [*Answer*], [*Who*]),
${myQa.map(r => `  [#rich(${parts(r.q)}, size: 9pt)], [#rich(${parts(r.a)}, size: 9pt)], [#text(9pt, ${q(r.who)})],`).join('\n')}
)

== My open items before the 25 Oct rehearsal

#table(columns: (auto, 1fr, auto, auto), stroke: 0.4pt + luma(200), inset: 5pt,
  table.header([*\\#*], [*Item*], [*Owner*], [*Slide*]),
${myItems.map(r => `  [${r[0]}], [#rich(${parts(r[1])}, size: 9pt)], [#text(9pt, ${q(r[2])})], [${r[3]}],`).join('\n')}
)

== On the day

- IDE open on ProductStatus, Product, ProductStatusTest and ProductLifecycleTest (rubric G10).
- Zoomable full ERD (src/diagrams/full-erd.svg) open in a browser tab for slide ${mine.find(s => /schema/i.test(s.title)).n}.
`;

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, t);
console.log('wrote', out, 'slides', mine.map(s => s.n).join(','), 'qa', myQa.length, 'items', myItems.length);
